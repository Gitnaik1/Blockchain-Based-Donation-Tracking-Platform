function getPermissionsForRoles(roles = []) {
  const permSet = new Set();
  for (const role of roles) {
    const perms = ROLE_PERMISSIONS[role] || [];
    for (const p of perms) {
      permSet.add(p);
    }
  }
  return Array.from(permSet);
}

